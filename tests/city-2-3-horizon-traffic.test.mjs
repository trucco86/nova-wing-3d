import { test } from 'node:test';
import assert from 'node:assert/strict';
import * as T from 'three';
import { createWorld } from '../src/visuals.js';
import { SECTORS } from '../src/campaign.js';

test('City 2.3 has a frontal three-tier skyline and elevated monument without gameplay colliders', () => {
  const scene = new T.Scene();
  const world = createWorld(scene, () => 0.5, true);
  const skyline = scene.getObjectByName('city-distant-horizon');
  assert.ok(skyline, 'independent forward-facing urban skyline');
  const towers = skyline.getObjectByName('city-horizon-tower-mass');
  assert.ok(towers?.isInstancedMesh);
  assert.ok(towers.count > 60 && towers.count <= 110);
  const monument = skyline.getObjectByName('city-horizon-monument');
  assert.ok(monument?.isGroup, 'central architectural destination');
  const centralSpan = monument.children[0];
  assert.ok(centralSpan.position.y - centralSpan.geometry.parameters.height / 2 > 100);
  assert.ok(monument.children.every((part) => !part.userData.hitbox));
  const high = skyline.getObjectByName('city-horizon-high-details');
  assert.ok(high.getObjectByName('city-horizon-window-bands').count > 140);
  world.setGraphicsQuality('medium');
  assert.equal(high.visible, false);
  assert.equal(towers.visible, true, 'Medium retains frontal city, not empty horizon');
  world.setGraphicsQuality('high');
  assert.equal(high.visible, true);
});

test('maglev and evac shuttles animate independently and honor graphics, phases and pause', () => {
  const scene = new T.Scene();
  const world = createWorld(scene, () => 0.5, true);
  const near = scene.getObjectByName('launch-city');
  const far = scene.getObjectByName('launch-city-far');
  const horizon = scene.getObjectByName('city-distant-horizon');
  const life = near.getObjectByName('city-urban-life');
  assert.ok(life);
  assert.equal(life.children.length, 11, '2 lateral maglevs, 1 overhead maglev, 1 guideway and 7 evacuation craft');
  assert.equal(far.getObjectByName('city-urban-life').children.length, 11);
  const west = near.getObjectByName('city-maglev-west');
  const east = near.getObjectByName('city-maglev-east');
  const craft = near.getObjectByName('city-evacuation-craft-0');
  assert.ok(west && east && craft);
  assert.ok(west.position.x <= -70 && east.position.x >= 70);
  const guideway = near.getObjectByName('city-suspended-transit');
  assert.ok(guideway?.isInstancedMesh);
  world.setGraphicsQuality('medium');
  assert.equal(west.visible, false);
  assert.equal(east.visible, true, 'introductory right-hand train must be visible in Medium');
  assert.equal(craft.visible, true);
  assert.equal(near.getObjectByName('city-evacuation-craft-6').visible, false);
  world.update(1, 2, 48, true);
  assert.notEqual(west.position.z, -520);
  assert.notEqual(craft.position.y, 38);
  assert.equal(guideway.visible, true, 'maglev tracks remain in Medium');
  const snapshot = [west.position.z, craft.position.y];
  world.update(2, 4, 48, false);
  assert.deepEqual([west.position.z, craft.position.y], snapshot, 'pause stops all urban motion');
  world.setGraphicsQuality('high');
  assert.equal(west.visible, true);
  assert.equal(east.visible, true);
  assert.equal(near.getObjectByName('city-evacuation-craft-6').visible, true);
  world.setSector(SECTORS[0]);
  assert.equal(horizon.visible, true);
  world.setLaunchAscent(0.85, true);
  assert.equal(horizon.visible, false, 'skyline disappears when Earth horizon takes over');
  world.setSector(SECTORS[1]);
  assert.equal(horizon.visible, false, 'no Earth skyline in ocean stage');
  assert.equal(life.visible, false, 'city evacuation is exclusive to the first urban sector');
  world.reset();
  assert.equal(horizon.position.z, 0);
  assert.ok(Number.isFinite(far.position.z));
});
