export const TROPHY_IDS = Object.freeze(TROPHIES.map((trophy) => trophy.id));
export const PRIMARY_TROPHIES = Object.freeze(
  TROPHIES.filter((trophy) => !trophy.secret && trophy.id !== 'platinum').map(
    (trophy) => trophy.id,
  ),
);

export function trophyProgress(definition, stats, unlocked = {}) {
  if (definition.metric === 'platinum')
    return PRIMARY_TROPHIES.reduce((total, id) => total + (unlocked[id] ? 1 : 0), 0);
  if (definition.metric.startsWith('boss-'))
    return stats.bossSectors.includes(Number(definition.metric.slice(5))) ? 1 : 0;
  if (definition.metric === 'marvin-primary') return stats.primaryBossSectors.includes(10) ? 1 : 0;
  if (definition.metric === 'cleared-sectors') return stats.clearSectors.length;
  if (definition.metric === 'hard-sectors') return stats.hardSectors.length;
  if (definition.metric === 'distinct-pilots') return stats.pilots.length;
  const key = {
    'total-points': 'points',
    'total-kills': 'kills',
    records: 'records',
    'clean-wins': 'cleanWins',
    'primary-bosses': 'primaryBosses',
    'bomb-free-wins': 'bombFreeWins',
    'fast-wins': 'fastWins',
    'mecha-finishes': 'mechaFinishes',
    'squad-wins': 'squadWins',
    rings: 'rings',
    'hard-perfect': 'hardPerfect',
    'hard-primary': 'hardPrimary',
  }[definition.metric];
  return Math.max(0, Number(stats[key]) || 0);
}
