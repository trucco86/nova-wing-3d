import { readFile, writeFile } from 'node:fs/promises';
import { build } from 'esbuild';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export async function bundleGame() {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ['src/main.js'],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: ['es2022'],
    minify: true,
    legalComments: 'inline',
  });
  const { version } = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
  const shell = await readFile(resolve(root, 'src/shell.html'), 'utf8');
  const css = await readFile(resolve(root, 'src/styles.css'), 'utf8');
  const cover = (await readFile(resolve(root, 'src/assets/cover.webp.base64'), 'utf8')).trim();
  const glb = (await readFile(resolve(root, 'src/assets/nova7-hero.glb.base64'), 'utf8')).trim();
  if (
    !/^[A-Za-z0-9+/]+=*$/.test(glb) ||
    Buffer.from(glb, 'base64').toString('ascii', 0, 4) !== 'glTF'
  )
    throw new Error('NOVA-7 GLB missing or invalid. Run npm run assets:prepare.');
  const js = result.outputFiles[0].text
    .replaceAll('__NOVA7_HERO_GLB_BASE64__', glb)
    .replaceAll('</script', '<\\/script');
  for (const marker of ['/* BUILD:STYLES */', '/* BUILD:GAME */', 'BUILD:VERSION'])
    if (!shell.includes(marker)) throw new Error(`Missing build marker: ${marker}`);
  return (
    '<!-- GENERATED from src/. Run npm run build. Do not edit this file. -->\n' +
    shell
      .replaceAll('BUILD:VERSION', version)
      .replace('/* BUILD:STYLES */', () =>
        css.replaceAll('BUILD:COVER', 'data:image/webp;base64,' + cover),
      )
      .replace('/* BUILD:GAME */', () => js)
    // The former Bia-only radio file is no longer embedded. The approved
    // Five Cats cover now provides all five speaker portraits.
  );
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const html = await bundleGame();
  if (process.argv.includes('--check')) {
    const actual = await readFile(resolve(root, 'index.html'), 'utf8').catch(() => '');
    if (actual !== html)
      throw new Error('index.html differs from src/. Run npm run build and commit the output.');
    console.log('Build is reproducible and synchronized.');
  } else {
    await writeFile(resolve(root, 'index.html'), html);
    console.log(`index.html generated (${Buffer.byteLength(html)} bytes).`);
  }
}
